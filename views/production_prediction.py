"""Production prediction page."""

from __future__ import annotations

import streamlit as st

from utils.inference import predict_production
from utils.loaders import (
    get_districts_for_state,
    get_filtered_production_options,
    load_production_artifacts,
    load_production_dataset,
)


def _format_number(value: float) -> str:
    """Format large production values for display."""
    if value >= 1_000_000:
        return f"{value / 1_000_000:.2f} M"
    if value >= 1_000:
        return f"{value / 1_000:.2f} K"
    return f"{value:,.2f}"


def render_production_prediction() -> None:
    """Render the production forecasting form and result card."""
    st.markdown(
        """
        <div class="page-header">
            <h1>Production Prediction</h1>
            <p>Forecast crop production using district-level historical patterns.</p>
        </div>
        """,
        unsafe_allow_html=True,
    )

    df = load_production_dataset()
    model, preprocessor = load_production_artifacts()

    col1, col2 = st.columns(2)
    with col1:
        states = sorted(df["State_Name"].dropna().unique().tolist())
        state = st.selectbox("State", options=[""] + states, format_func=lambda x: x or "Select state")
        districts = get_districts_for_state(df, state) if state else []
        district = st.selectbox(
            "District",
            options=[""] + districts,
            format_func=lambda x: x or "Select district",
            disabled=not state,
        )
        crop_year_options = get_filtered_production_options(df, state, district or None)["years"]
        crop_year = st.selectbox(
            "Crop Year",
            options=crop_year_options if crop_year_options else [2000],
            disabled=not state,
        )

    filtered = get_filtered_production_options(df, state or None, district or None)
    with col2:
        seasons = filtered["seasons"] if filtered["seasons"] else sorted(df["Season"].unique().tolist())
        season = st.selectbox(
            "Season",
            options=[""] + seasons,
            format_func=lambda x: x.strip() if x else "Select season",
            disabled=not state,
        )
        crops = filtered["crops"] if filtered["crops"] else sorted(df["Crop"].unique().tolist())
        crop = st.selectbox(
            "Crop",
            options=[""] + crops,
            format_func=lambda x: x or "Select crop",
            disabled=not state,
        )
        area = st.number_input(
            "Area (hectares)",
            min_value=0.0,
            value=100.0,
            step=10.0,
            format="%.2f",
        )

    if st.button("Predict Production", use_container_width=True):
        result = predict_production(
            model,
            preprocessor,
            state,
            district,
            int(crop_year),
            season,
            crop,
            area,
        )
        if "error" in result:
            st.error(result["error"])
            return

        production = result["production"]
        st.markdown(
            f"""
            <div class="result-card">
                <div class="result-label">Predicted Production</div>
                <p class="result-value">{_format_number(production)}</p>
                <div class="result-meta">
                    {crop} · {district}, {state}<br>
                    {season.strip()} · {crop_year} · {area:,.2f} ha
                </div>
            </div>
            """,
            unsafe_allow_html=True,
        )

        detail_col1, detail_col2, detail_col3 = st.columns(3)
        with detail_col1:
            st.metric("Exact Value", f"{production:,.2f}")
        with detail_col2:
            st.metric("Area", f"{area:,.2f} ha")
        with detail_col3:
            st.metric("Yield / ha", f"{production / area:,.2f}" if area > 0 else "N/A")

    with st.expander("About this model"):
        st.markdown(
            """
            Predictions are generated by a pre-trained **XGBoost** regressor (R² ≈ 0.96)
            using state, district, crop year, season, crop type, and cultivated area.
            Dropdown values are populated dynamically from the production dataset.
            """
        )
